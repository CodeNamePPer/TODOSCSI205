export const fetchPhotos = async (): Promise<PhotoType[]> => {
    try {
        const response = await fetch("https://jsonplaceholder.typicode.com/photos?_limit=123");
        if (!response.ok) {
            throw new Error(`HTTP error! status: ${response.status}`);
        }
        const apiData = await response.json();
        return apiData.map((item: any) => ({
            ...item,
            price: photos.find(p => p.id === item.id)?.price || item.id * 1.5,
        }));
    } catch (error) {
        console.error("Failed to fetch photos from API, using mock photos:", error);
        return photos;
    }
};
